// Writes engine/math/src/color_names.rs from Color.NAMES in three@0.186.1 src/math/Color.js,
// so the keyword table is never transcribed by hand.
//
// Run:  node parity/math/gen/gen_color_names.mjs

import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Color } from 'three/src/math/Color.js';

const out = fileURLToPath( new URL( '../../../engine/math/src/color_names.rs', import.meta.url ) );
const names = Object.entries( Color.NAMES ).sort( ( a, b ) => ( a[ 0 ] < b[ 0 ] ? - 1 : 1 ) );
const hex = ( n ) => '0x' + n.toString( 16 ).toUpperCase().padStart( 6, '0' );

fs.writeFileSync( out, `// GENERATED by parity/math/gen/gen_color_names.mjs. Do not edit by hand.

pub const NAMES: [(&str, u32); ${names.length}] = [
${names.map( ( [ k, v ] ) => `    ("${k}", ${hex( v )}),` ).join( '\n' )}
];
` );
console.log( `${names.length} colour names -> ${out}` );
